"""
Cryptographic Fake HTTP Header and Decoy Cookie Generator
(`honey_token_injector.fake_header_generator`).

Generates realistic enterprise debug/staging HTTP headers and decoy session cookies
signed with HMAC-SHA256 so any replay by an adversary or scanner is deterministically
identified at the Deception Gateway (`deception_gateway`).
"""

from __future__ import annotations

import hashlib
import hmac
import os
import secrets
from datetime import datetime, timedelta, timezone
from typing import Dict, List, Optional, Tuple

from shared_contracts.honey_token_schema import (
    HoneyTokenCreateContract,
    HoneyTokenTypeEnum,
    InjectionVectorEnum,
)

DEFAULT_HONEY_HMAC_SECRET: str = os.getenv(
    "HONEY_TOKEN_HMAC_SECRET",
    "deception_honey_token_hmac_sha256_master_secret_2026",
)

# Realistic header lures: (header_name, value_prefix, associated_decoy_path)
HEADER_LURE_TEMPLATES: List[Tuple[str, str, str]] = [
    (
        "X-Internal-Debug-Token",
        "dbg_live",
        "/api/v1/internal/debug-console",
    ),
    (
        "X-Staging-API-Key",
        "stg_ak",
        "/api/v1/internal/vault-keys",
    ),
    (
        "X-Admin-Trace-Session",
        "trc_adm",
        "/admin/debug/env-dump",
    ),
    (
        "X-Vault-Unseal-Ticket",
        "vlt_root",
        "/api/v1/backup/db-snapshot",
    ),
]


class FakeHeaderGenerator:
    """
    Generates HMAC-SHA256 signed decoy HTTP headers (`FAKE_HTTP_HEADER`) and decoy
    session cookies (`DECOY_SESSION_COOKIE`) conforming strictly to
    `HoneyTokenCreateContract`.
    """

    def __init__(
        self,
        secret_key: Optional[str] = None,
        default_ttl_hours: int = 24,
    ) -> None:
        """
        Initialize the fake header generator with an HMAC signing key and token registry.

        Args:
            secret_key: Secret key used for HMAC-SHA256 decoy token signatures.
            default_ttl_hours: Default validity window for generated honey tokens in hours.
        """
        self._secret_bytes: bytes = (
            secret_key or DEFAULT_HONEY_HMAC_SECRET
        ).encode("utf-8")
        self._default_ttl_hours: int = max(1, default_ttl_hours)
        self._issued_tokens: Dict[str, HoneyTokenCreateContract] = {}
        self._value_to_token_id: Dict[str, str] = {}

    def _compute_hmac_tag(self, token_id: str, nonce: str) -> str:
        """Compute a 16-character hexadecimal HMAC-SHA256 tag over `token_id:nonce`."""
        message = f"{token_id}:{nonce}".encode("utf-8")
        digest = hmac.new(self._secret_bytes, message, hashlib.sha256).hexdigest()
        return digest[:16]

    def build_signed_decoy_value(self, prefix: str, token_id: str) -> str:
        """
        Build a self-verifiable decoy credential value embedding `token_id`, a random
        nonce, and an HMAC-SHA256 tag: `<prefix>_<short_id>_<nonce>_<hmac16>`.
        """
        short_id = token_id.replace("htk_", "")
        nonce = secrets.token_hex(4)
        mac_tag = self._compute_hmac_tag(short_id, nonce)
        return f"{prefix}_{short_id}_{nonce}_{mac_tag}"

    def verify_signed_decoy_value(self, candidate_value: str) -> Optional[str]:
        """
        Verify whether `candidate_value` carries a valid HMAC-SHA256 signature
        generated by this class.

        Args:
            candidate_value: Header, cookie, or token string presented by a client.

        Returns:
            Reconstructed `token_id` (`htk_<short_id>`) if valid, else `None`.
        """
        if not candidate_value or not isinstance(candidate_value, str):
            return None

        cleaned = candidate_value.strip()
        if cleaned in self._value_to_token_id:
            return self._value_to_token_id[cleaned]

        parts = cleaned.split("_")
        if len(parts) < 5:
            return None

        provided_mac = parts[-1]
        nonce = parts[-2]
        short_id = parts[-3]
        if not short_id or not nonce or len(provided_mac) != 16:
            return None

        expected_mac = self._compute_hmac_tag(short_id, nonce)
        if hmac.compare_digest(expected_mac, provided_mac.lower()):
            return f"htk_{short_id}"
        return None

    def generate_header_token(
        self,
        header_name: Optional[str] = None,
        target_url_path: Optional[str] = None,
        ttl_hours: Optional[int] = None,
    ) -> HoneyTokenCreateContract:
        """
        Generate a single `FAKE_HTTP_HEADER` honey token contract ready for injection
        into outgoing HTTP response headers.

        Args:
            header_name: Optional custom header name (e.g., `X-Internal-Debug-Token`).
            target_url_path: Optional decoy path associated with the header.
            ttl_hours: Optional expiration lifetime in hours.

        Returns:
            Validated `HoneyTokenCreateContract` instance.
        """
        template_idx = secrets.randbelow(len(HEADER_LURE_TEMPLATES))
        default_header, prefix, default_path = HEADER_LURE_TEMPLATES[template_idx]

        chosen_header = header_name or default_header
        chosen_path = target_url_path or default_path
        short_id = secrets.token_hex(6)
        token_id = f"htk_{short_id}"
        decoy_value = self.build_signed_decoy_value(prefix, token_id)

        now_utc = datetime.now(timezone.utc)
        expires_utc = now_utc + timedelta(
            hours=ttl_hours if ttl_hours is not None else self._default_ttl_hours
        )

        contract = HoneyTokenCreateContract(
            token_id=token_id,
            token_type=HoneyTokenTypeEnum.FAKE_HTTP_HEADER,
            injection_vector=InjectionVectorEnum.RESPONSE_HEADER,
            header_or_field_name=chosen_header,
            decoy_value=decoy_value,
            target_url_path=chosen_path,
            created_at=now_utc,
            expires_at=expires_utc,
        )
        self._issued_tokens[contract.token_id] = contract
        self._value_to_token_id[contract.decoy_value] = contract.token_id
        return contract

    def generate_decoy_cookie_token(
        self,
        cookie_name: str = "enterprise_debug_sid",
        target_url_path: str = "/admin/debug/env-dump",
        ttl_hours: Optional[int] = None,
    ) -> HoneyTokenCreateContract:
        """
        Generate a `DECOY_SESSION_COOKIE` honey token contract for `Set-Cookie`
        response header injection.

        Args:
            cookie_name: Name of the decoy cookie.
            target_url_path: Monitored decoy endpoint path.
            ttl_hours: Optional expiration lifetime in hours.

        Returns:
            Validated `HoneyTokenCreateContract` instance.
        """
        short_id = secrets.token_hex(6)
        token_id = f"htk_{short_id}"
        decoy_value = self.build_signed_decoy_value("dsid_priv", token_id)

        now_utc = datetime.now(timezone.utc)
        expires_utc = now_utc + timedelta(
            hours=ttl_hours if ttl_hours is not None else self._default_ttl_hours
        )

        contract = HoneyTokenCreateContract(
            token_id=token_id,
            token_type=HoneyTokenTypeEnum.DECOY_SESSION_COOKIE,
            injection_vector=InjectionVectorEnum.RESPONSE_HEADER,
            header_or_field_name=cookie_name,
            decoy_value=decoy_value,
            target_url_path=target_url_path,
            created_at=now_utc,
            expires_at=expires_utc,
        )
        self._issued_tokens[contract.token_id] = contract
        self._value_to_token_id[contract.decoy_value] = contract.token_id
        return contract

    def generate_header_bundle(self, count: int = 2) -> List[HoneyTokenCreateContract]:
        """
        Generate a bundle of distinct `FAKE_HTTP_HEADER` honey tokens for response
        enrichment.

        Args:
            count: Number of distinct fake headers to generate (clamped to available templates).

        Returns:
            List of `HoneyTokenCreateContract` instances.
        """
        effective_count = max(1, min(count, len(HEADER_LURE_TEMPLATES)))
        contracts: List[HoneyTokenCreateContract] = []
        for idx in range(effective_count):
            hdr_name, prefix, target_path = HEADER_LURE_TEMPLATES[idx]
            short_id = secrets.token_hex(6)
            token_id = f"htk_{short_id}"
            decoy_val = self.build_signed_decoy_value(prefix, token_id)
            now_utc = datetime.now(timezone.utc)
            contract = HoneyTokenCreateContract(
                token_id=token_id,
                token_type=HoneyTokenTypeEnum.FAKE_HTTP_HEADER,
                injection_vector=InjectionVectorEnum.RESPONSE_HEADER,
                header_or_field_name=hdr_name,
                decoy_value=decoy_val,
                target_url_path=target_path,
                created_at=now_utc,
                expires_at=now_utc + timedelta(hours=self._default_ttl_hours),
            )
            self._issued_tokens[contract.token_id] = contract
            self._value_to_token_id[contract.decoy_value] = contract.token_id
            contracts.append(contract)
        return contracts

    def get_issued_tokens(self) -> Dict[str, HoneyTokenCreateContract]:
        """Return a copy of all issued header and cookie honey tokens."""
        return dict(self._issued_tokens)
